// Builds every token output from the model in tokens/index.mjs.
//
//   node scripts/build-tokens.mjs          write src/styles/tokens.generated.css and dist/tokens.*
//   node scripts/build-tokens.mjs --check  fail if src/styles/tokens.generated.css is stale
//
// src/styles/tokens.generated.css is committed (the components and the demo import it), so the
// check keeps it in step with the model. dist/ gets the same CSS plus SCSS, JS, .d.ts and a
// DTCG-shaped JSON file for design tools.
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  axes,
  BREAKPOINTS,
  knobs,
  legacyAlias,
  mediaDefaults,
  palettes,
  tokens,
} from '../tokens/index.mjs';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const legacyNames = JSON.parse(await readFile(path.join(rootDir, 'tokens/legacy-names.json'), 'utf8'));
const pkg = JSON.parse(await readFile(path.join(rootDir, 'package.json'), 'utf8'));

export const GENERATED_CSS = path.join(rootDir, 'src/styles/tokens.generated.css');
const distDir = path.join(rootDir, 'dist');

const REF = /var\(--pada-([\w-]+)\)/g;
const refsOf = (value) => [...value.matchAll(REF)].map((match) => match[1]);

// ── Scope analysis ───────────────────────────────────────────────────────────────────────────
// A token is "computed" when its value depends on a knob or a palette. Computed tokens are
// re-declared on every element that sets an axis attribute, because var() inside a custom
// property is substituted where the property is declared, not where it is used.
const AXIS_ATTRIBUTES = Object.keys(axes).map((axis) => `data-${axis}`);
const dynamic = new Set([...knobs, ...palettes].map((token) => token.name));
const byName = new Map(tokens.map((token) => [token.name, token]));
{
  const seen = new Set();
  for (const { name } of [...knobs, ...palettes, ...tokens]) {
    if (seen.has(name)) throw new Error(`tokens/index.mjs: --pada-${name} is defined twice`);
    seen.add(name);
  }
}

const computed = new Set();
const isComputed = (name, seen = new Set()) => {
  if (dynamic.has(name) || computed.has(name)) return true;
  const token = byName.get(name);
  if (!token || seen.has(name)) return false;
  seen.add(name);
  return refsOf(token.value).some((ref) => isComputed(ref, seen));
};
for (const token of tokens) if (isComputed(token.name)) computed.add(token.name);

const legacy = legacyNames.map((name) => {
  const value = legacyAlias(name);
  if (value === null) throw new Error(`tokens/index.mjs: no 2.0 alias for legacy token ${name}`);
  return { name: name.replace(/^--/, ''), value, legacy: true };
});
const legacyIsComputed = (token) => refsOf(token.value).some((ref) => isComputed(ref));

// ── CSS ──────────────────────────────────────────────────────────────────────────────────────
const decl = (name, value) => `  --${name.startsWith('pada-') ? name : `pada-${name}`}: ${value};`;
const legacyDecl = (token) => `  --${token.name}: ${token.value};`;
const block = (selector, lines) => `${selector} {\n${lines.join('\n')}\n}`;

function renderCss() {
  const rootTokens = tokens.filter((token) => !computed.has(token.name));
  const computedTokens = tokens.filter((token) => computed.has(token.name));
  const sections = [
    `/* Pada design tokens v${pkg.version}. Generated by scripts/build-tokens.mjs from tokens/; do not edit. */`,
    '',
    '/* Knobs, palettes and constant tokens. color-scheme "light dark" lets light-dark() follow the OS. */',
    block(':root', [
      '  color-scheme: light dark;',
      '',
      '  /* Knobs */',
      ...knobs.map((token) => decl(token.name, token.value)),
      '',
      '  /* Palettes (reassigned by data-accent and data-neutral) */',
      ...palettes.map((token) => decl(token.name, token.value)),
      '',
      '  /* Constant tokens */',
      ...rootTokens.map((token) => decl(token.name, token.value)),
    ]),
    '',
    '/* Themes: light-dark() picks a branch from the element\'s color-scheme */',
    block(':root[data-theme="light"],\n[data-theme="light"]', ['  color-scheme: light;']),
    block(':root[data-theme="dark"],\n[data-theme="dark"]', ['  color-scheme: dark;']),
    '',
    '/* User preferences set knobs before any attribute does */',
    ...mediaDefaults.map(({ query, knobs: values }) =>
      `@media ${query} {\n${block('  :root', Object.entries(values).map(([name, value]) => `  ${decl(name, value)}`)).replace(/\n}$/, '\n  }')}\n}`,
    ),
    '',
    '/* Theme axes */',
    ...Object.entries(axes).flatMap(([axis, options]) =>
      Object.entries(options).map(([option, values]) =>
        block(`[data-${axis}="${option}"]`, Object.entries(values).map(([name, value]) => decl(name, value))),
      ),
    ),
    '',
    '/* Tokens that read a knob or a palette, re-declared wherever an axis attribute changes one */',
    block([':root', ...AXIS_ATTRIBUTES.map((attribute) => `[${attribute}]`)].join(',\n'), [
      ...computedTokens.map((token) => decl(token.name, token.value)),
      '',
      '  /* Pada 1.x names (deprecated, removed in 3.0) */',
      ...legacy.filter(legacyIsComputed).map(legacyDecl),
    ]),
    '',
    '/* Pada 1.x names (deprecated, removed in 3.0) */',
    block(':root', legacy.filter((token) => !legacyIsComputed(token)).map(legacyDecl)),
    '',
  ];
  return sections.join('\n');
}

// ── Value resolution for JSON (default knobs, light and dark) ────────────────────────────────
const defaults = new Map(
  [...knobs, ...palettes, ...tokens].map((token) => [token.name, token.value]),
);

function splitArgs(inner) {
  const args = [];
  let depth = 0;
  let current = '';
  for (const char of inner) {
    if (char === '(') depth += 1;
    if (char === ')') depth -= 1;
    if (char === ',' && depth === 0) {
      args.push(current.trim());
      current = '';
    } else current += char;
  }
  args.push(current.trim());
  return args;
}

function resolve(value, scheme, depth = 0) {
  if (depth > 20) return value;
  let out = value.replace(REF, (whole, name) => (defaults.has(name) ? resolve(defaults.get(name), scheme, depth + 1) : whole));
  let index;
  while ((index = out.indexOf('light-dark(')) !== -1) {
    let depthCount = 0;
    let end = index + 'light-dark('.length;
    for (; end < out.length; end += 1) {
      if (out[end] === '(') depthCount += 1;
      if (out[end] === ')') {
        if (depthCount === 0) break;
        depthCount -= 1;
      }
    }
    const [light, dark] = splitArgs(out.slice(index + 'light-dark('.length, end));
    out = out.slice(0, index) + (scheme === 'dark' ? dark : light) + out.slice(end + 1);
  }
  return out;
}

const DTCG_TYPES = {
  color: 'color', dimension: 'dimension', fontFamily: 'fontFamily', fontWeight: 'fontWeight',
  duration: 'duration', cubicBezier: 'cubicBezier', number: 'number', shadow: 'shadow',
  gradient: 'gradient',
};

function renderJson() {
  const entry = (token) => {
    const light = resolve(token.value, 'light');
    const dark = resolve(token.value, 'dark');
    return {
      $type: DTCG_TYPES[token.type] ?? 'string',
      $value: light,
      ...(token.description ? { $description: token.description } : {}),
      $extensions: {
        'design.pada': {
          cssVariable: `--pada-${token.name}`,
          tier: token.tier,
          expression: token.value,
          ...(dark !== light ? { dark } : {}),
        },
      },
    };
  };
  const group = (list) => Object.fromEntries(list.map((token) => [token.name, entry(token)]));
  return JSON.stringify(
    {
      $description: `Pada design tokens v${pkg.version}. $value is the light theme with default knobs; expression is the CSS source.`,
      knob: group(knobs),
      palette: group(palettes),
      token: group(tokens),
    },
    null,
    2,
  );
}

// ── SCSS, JS, d.ts ───────────────────────────────────────────────────────────────────────────
const allNames = [...knobs, ...tokens].map((token) => token.name);

function renderScss() {
  return [
    `// Pada design tokens v${pkg.version}. Generated by scripts/build-tokens.mjs; do not edit.`,
    '// The values live in tokens.css; this file gives Sass access to breakpoints and token names.',
    '',
    `$pada-breakpoints: (${Object.entries(BREAKPOINTS).map(([name, px]) => `'${name}': ${px}px`).join(', ')});`,
    '',
    '// Media query at or above a breakpoint: @include pada-up(md) { … }',
    '@mixin pada-up($name) {',
    '  @media (min-width: map-get($pada-breakpoints, $name)) {',
    '    @content;',
    '  }',
    '}',
    '',
    '// Media query below a breakpoint: @include pada-down(md) { … }',
    '@mixin pada-down($name) {',
    '  @media (max-width: map-get($pada-breakpoints, $name) - 0.02px) {',
    '    @content;',
    '  }',
    '}',
    '',
    '$pada-tokens: (',
    ...allNames.map((name) => `  '${name}': var(--pada-${name}),`),
    ');',
    '',
    '// Token reference by name: color: pada(color-fg-muted);',
    '@function pada($name) {',
    '  @if not map-has-key($pada-tokens, $name) {',
    '    @error "Unknown Pada token: #{$name}";',
    '  }',
    '  @return map-get($pada-tokens, $name);',
    '}',
    '',
  ].join('\n');
}

function renderJs() {
  return [
    `// Pada design tokens v${pkg.version}. Generated by scripts/build-tokens.mjs; do not edit.`,
    '/** Every token name mapped to its CSS var() reference. */',
    `export const tokens = Object.freeze(${JSON.stringify(Object.fromEntries(allNames.map((name) => [name, `var(--pada-${name})`])), null, 2)});`,
    '/** Breakpoints in px, for JS media queries. */',
    `export const breakpoints = Object.freeze(${JSON.stringify(BREAKPOINTS)});`,
    '/** Theme axis attributes and their allowed values. */',
    `export const themeAxes = Object.freeze(${JSON.stringify(Object.fromEntries(Object.entries(axes).map(([axis, options]) => [axis, Object.keys(options)])))});`,
    '',
  ].join('\n');
}

function renderDts() {
  return [
    `// Pada design tokens v${pkg.version}. Generated by scripts/build-tokens.mjs; do not edit.`,
    `export type TokenName =\n${allNames.map((name) => `  | '${name}'`).join('\n')};`,
    '/** Every token name mapped to its CSS var() reference. */',
    'export declare const tokens: Readonly<Record<TokenName, string>>;',
    `export declare const breakpoints: Readonly<{ ${Object.keys(BREAKPOINTS).map((name) => `'${name}': number`).join('; ')} }>;`,
    `export type ThemeAxes = {\n${Object.entries(axes).map(([axis, options]) => `  ${axis}: ${Object.keys(options).map((option) => `'${option}'`).join(' | ')};`).join('\n')}\n};`,
    'export declare const themeAxes: Readonly<{ [K in keyof ThemeAxes]: readonly ThemeAxes[K][] }>;',
    '',
  ].join('\n');
}

export const contentHash = (text) => createHash('sha256').update(text).digest('hex').slice(0, 16);

export function buildOutputs() {
  return {
    css: renderCss(),
    scss: renderScss(),
    js: renderJs(),
    dts: renderDts(),
    json: `${renderJson()}\n`,
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const outputs = buildOutputs();
  if (process.argv.includes('--check')) {
    const current = await readFile(GENERATED_CSS, 'utf8').catch(() => '');
    if (current !== outputs.css) {
      console.error('src/styles/tokens.generated.css is stale. Run `npm run build:tokens`.');
      process.exit(1);
    }
    console.log('src/styles/tokens.generated.css is up to date.');
  } else {
    await writeFile(GENERATED_CSS, outputs.css, 'utf8');
    console.log(`Generated ${path.relative(rootDir, GENERATED_CSS)}`);
    if (!process.argv.includes('--src-only')) {
      await mkdir(distDir, { recursive: true });
      const base = await readFile(path.join(rootDir, 'src/styles/base.css'), 'utf8');
      const files = {
        'tokens.css': outputs.css,
        'tokens.scss': outputs.scss,
        'tokens.js': outputs.js,
        'tokens.d.ts': outputs.dts,
        'tokens.json': outputs.json,
        'base.css': `/* pada-ds optional base styles */\n${base.trim()}\n`,
      };
      for (const [file, text] of Object.entries(files)) {
        await writeFile(path.join(distDir, file), text, 'utf8');
        console.log(`Generated dist/${file}`);
      }
    }
  }
}
